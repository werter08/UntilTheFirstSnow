using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Courtyard.Core;
using Courtyard.Story;
using TMPro;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace Courtyard.Editor
{
    /// <summary>
    /// Writes every player-facing text in the game into one file (Docs/Texts.md) for proofreading: story beats per day,
    /// step hints, calendar lines, fridge notes, cold / fail lines, the ending, and the fixed texts in the scenes.
    /// Read-only: it never changes assets or scenes. Edit texts in the assets, then export again.
    /// </summary>
    internal static class TextsExporter
    {
        private const string OutputPath = "Docs/Texts.md";

        [MenuItem("Courtyard/Export Texts (Docs/Texts.md)")]
        public static void Export()
        {
            var md = new StringBuilder();
            md.AppendLine("# Until the First Snow — all texts");
            md.AppendLine();
            md.AppendLine("_Generated by **Courtyard → Export Texts**. Don't edit here: change the asset named in each section, then export again._");
            md.AppendLine();

            var levels = AssetDatabase.FindAssets("t:LevelDefinition", new[] { "Assets/_Game/Data" })
                .Select(AssetDatabase.GUIDToAssetPath).Select(AssetDatabase.LoadAssetAtPath<LevelDefinition>)
                .Where(l => l != null).OrderBy(l => l.DayNumber).ToList();
            foreach (var level in levels) WriteDay(md, level);

            md.AppendLine("## Fridge notes");
            md.AppendLine();
            foreach (var book in Assets<NotesBook>())
            {
                md.AppendLine($"_{AssetDatabase.GetAssetPath(book)}_").AppendLine();
                var notes = new SerializedObject(book).FindProperty("notes");
                for (var i = 0; i < notes.arraySize; i++)
                {
                    var note = notes.GetArrayElementAtIndex(i);
                    var from = note.FindPropertyRelative("from").stringValue;
                    md.AppendLine($"- **After day {note.FindPropertyRelative("afterDay").intValue}**" +
                                  (string.IsNullOrEmpty(from) ? "" : $" (from {from})") + $": {Inline(note.FindPropertyRelative("text").stringValue)}");
                }

                md.AppendLine();
            }

            foreach (var sequence in Assets<StorySequence>())
            {
                md.AppendLine($"## {ObjectNames.NicifyVariableName(sequence.name)} (story sequence)");
                md.AppendLine();
                md.AppendLine($"_{AssetDatabase.GetAssetPath(sequence)}_").AppendLine();
                WriteBeats(md, new SerializedObject(sequence).FindProperty("beats"));
            }

            md.AppendLine("## Fixed texts in the scenes");
            md.AppendLine();
            md.AppendLine("Title screen prompt, HUD labels, hints set on components, the ending's credits, …");
            md.AppendLine();
            foreach (var path in BuildScript.Scenes) WriteScene(md, path);

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath)!);
            File.WriteAllText(OutputPath, md.ToString());
            Debug.Log($"TextsExporter: wrote {OutputPath} ({levels.Count} days).");
        }

        private static IEnumerable<T> Assets<T>() where T : Object =>
            AssetDatabase.FindAssets($"t:{typeof(T).Name}", new[] { "Assets/_Game/Data" })
                .Select(AssetDatabase.GUIDToAssetPath).Select(AssetDatabase.LoadAssetAtPath<T>).Where(a => a != null);

        private static void WriteDay(StringBuilder md, LevelDefinition level)
        {
            md.AppendLine($"## Day {level.DayNumber} — {level.ClockTime}");
            md.AppendLine();
            md.AppendLine($"_{AssetDatabase.GetAssetPath(level)}_").AppendLine();
            md.AppendLine($"- **Calendar page:** {Inline(level.CalendarLine)}");
            md.AppendLine($"- **Bad drink (cold):** {Inline(level.ColdDrinkText)}");
            md.AppendLine($"- **Too cold (fail):** {Inline(level.FailText)}");
            md.AppendLine();

            md.AppendLine("**Steps and their hints**").AppendLine();
            for (var i = 0; i < level.Steps.Count; i++)
            {
                var step = level.Steps[i];
                md.AppendLine(step == null ? $"{i}. _(missing)_" : $"{i}. {step.name} — {Inline(step.HintText)}");
            }

            md.AppendLine();
            md.AppendLine("**Story**").AppendLine();
            WriteBeats(md, new SerializedObject(level).FindProperty("storyBeats"));
        }

        private static void WriteBeats(StringBuilder md, SerializedProperty beats)
        {
            if (beats == null || beats.arraySize == 0)
            {
                md.AppendLine("_(none)_").AppendLine();
                return;
            }

            md.AppendLine("| When | Style | Who | Text |");
            md.AppendLine("|---|---|---|---|");
            for (var i = 0; i < beats.arraySize; i++)
            {
                var beat = beats.GetArrayElementAtIndex(i);
                var trigger = (BeatTrigger)beat.FindPropertyRelative("trigger").enumValueIndex;
                var when = trigger == BeatTrigger.AfterStep ? $"AfterStep({beat.FindPropertyRelative("stepIndex").intValue})" : trigger.ToString();
                var condition = (BeatCondition)beat.FindPropertyRelative("condition").enumValueIndex;
                if (condition != default) when += $" · {condition}";
                var style = (BeatStyle)beat.FindPropertyRelative("style").enumValueIndex;
                md.AppendLine($"| {when} | {style} | {Cell(beat.FindPropertyRelative("speaker").stringValue)} | {Cell(beat.FindPropertyRelative("text").stringValue)} |");
            }

            md.AppendLine();
        }

        /// <summary>Texts written into a scene: TextMeshPro labels and the string fields of the game's own components.</summary>
        private static void WriteScene(StringBuilder md, string path)
        {
            var scene = EditorSceneManager.GetSceneByPath(path);
            var opened = !scene.isLoaded;
            if (opened) scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Additive);
            try
            {
                var lines = new List<string>();
                foreach (var root in scene.GetRootGameObjects())
                {
                    foreach (var text in root.GetComponentsInChildren<TMP_Text>(true))
                        if (IsWords(text.text)) lines.Add($"- `{text.name}`: {Inline(text.text)}");

                    foreach (var component in root.GetComponentsInChildren<MonoBehaviour>(true))
                    {
                        if (component == null || component is TMP_Text || component.GetType().Namespace?.StartsWith("Courtyard") != true) continue;
                        var property = new SerializedObject(component).GetIterator();
                        while (property.NextVisible(true))
                            if (property.propertyType == SerializedPropertyType.String && IsTextField(property.name) && IsWords(property.stringValue))
                                lines.Add($"- `{component.GetType().Name}.{property.propertyPath}`: {Inline(property.stringValue)}");
                    }
                }

                md.AppendLine($"### {Path.GetFileNameWithoutExtension(path)}");
                md.AppendLine();
                foreach (var line in lines.Distinct()) md.AppendLine(line);
                md.AppendLine();
            }
            finally
            {
                if (opened) EditorSceneManager.CloseScene(scene, true);
            }
        }

        private static readonly string[] TextFieldWords = { "text", "hint", "line", "prompt", "title", "label", "message", "caption", "credit", "speaker" };

        /// <summary>Fields meant for the player (not layer names, paths or ids).</summary>
        private static bool IsTextField(string name) => TextFieldWords.Any(w => name.ToLowerInvariant().Contains(w));

        /// <summary>Real words, not numbers, times or placeholders.</summary>
        private static bool IsWords(string value) => !string.IsNullOrWhiteSpace(value) && value.Count(char.IsLetter) >= 3;

        private static string Inline(string value) =>
            string.IsNullOrWhiteSpace(value) ? "_(empty)_" : value.Trim().Replace("\r", "").Replace("\n", " / ");

        private static string Cell(string value) => string.IsNullOrEmpty(value) ? "" : Inline(value).Replace("|", "\\|");
    }
}
